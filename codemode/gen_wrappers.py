#!/usr/bin/env python3
"""Generate ./servers/<server>/<tool>.py wrappers from an MCP server's tools/list.

    python3 codemode/gen_wrappers.py cloudflare_api                 # live (needs auth)
    python3 codemode/gen_wrappers.py cloudflare_api --from FILE.json # from a saved tools/list

One file per tool, one-line description first, typed parameters from the
input schema. Policy is not generated; it lives in runtime/policy.py so a
regeneration can never drop a guard. A live run also refreshes
servers/<server>/tools.snapshot.json so tool-surface changes show up in review.
"""

from __future__ import annotations

import json
import keyword
import re
import sys
import textwrap
from pathlib import Path
from typing import Any

KIT = Path(__file__).resolve().parent
sys.path.insert(0, str(KIT.parent))

from codemode.runtime import config  # noqa: E402

_PY = {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "object": "dict[str, Any]"}


def ident(name: str) -> str:
    out = re.sub(r"\W+", "_", re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)).strip("_").lower() or "tool"
    if out[0].isdigit():
        out = "t_" + out
    return out + "_" if keyword.iskeyword(out) else out


def py_type(schema: dict[str, Any]) -> str:
    if "enum" in schema and all(isinstance(v, str) for v in schema["enum"]):
        return "Literal[" + ", ".join(repr(v) for v in schema["enum"]) + "]"
    kind = schema.get("type")
    if isinstance(kind, list):
        kinds = [k for k in kind if k != "null"]
        kind = kinds[0] if len(kinds) == 1 else None
    if kind == "array":
        return f"list[{py_type(schema.get('items') or {})}]"
    return _PY.get(kind or "", "Any")


def one_line(text: str, fallback: str) -> str:
    text = " ".join((text or "").split())
    if not text:
        return fallback
    first = re.split(r"(?<=[.!?])\s", text, maxsplit=1)[0]
    return first if len(first) <= 200 else first[:197] + "..."


def _doc(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')


def render(server: str, tool: dict[str, Any], source: str) -> tuple[str, str]:
    name = tool["name"]
    fn = ident(name)
    schema = tool.get("inputSchema") or {}
    props: dict[str, Any] = schema.get("properties") or {}
    required = [p for p in schema.get("required", []) if p in props]
    optional = [p for p in props if p not in required]
    params, mapping, arg_docs = [], [], []
    for p in required:
        params.append(f"{ident(p)}: {py_type(props[p])}")
    if optional:
        params.append("*")
        for p in optional:
            params.append(f"{ident(p)}: {py_type(props[p])} | None = None")
    for p in required + optional:
        mapping.append(f"{p!r}: {ident(p)}")
        desc = " ".join((props[p].get("description") or "").split())
        arg_docs.append(f"    {ident(p)}: {desc}" if desc else f"    {ident(p)}")
    summary = one_line(tool.get("description", ""), f"{name} on {server}")
    body_doc = textwrap.fill(" ".join((tool.get("description") or "").split()), 92)
    doc = body_doc + ("\n\nArgs:\n" + "\n".join(arg_docs) if arg_docs else "")
    uses_literal = any("Literal[" in x for x in params)
    typing_imports = "Any, Literal" if uses_literal else "Any"
    src = f'''"""{_doc(summary)}"""
# Generated by codemode/gen_wrappers.py from {source}. Do not edit; regenerate.
# Repo policy for this tool, if any, is enforced in codemode/runtime/policy.py.

from __future__ import annotations

from typing import {typing_imports}

from codemode.runtime.mcp import call_tool

SERVER = {server!r}
TOOL = {name!r}
ANNOTATIONS: dict[str, Any] = {dict(sorted((tool.get("annotations") or {}).items()))!r}


def {fn}({", ".join(params)}) -> Any:
    """{_doc(textwrap.indent(doc, "    ").strip())}
    """
    return call_tool(SERVER, TOOL, {{{", ".join(mapping)}}})
'''
    return fn, src


def generate(server: str, tools: list[dict[str, Any]], source: str) -> list[str]:
    spec = config()["servers"].get(server, {})
    skip = set(spec.get("skip_tools", []))
    out_dir = KIT / "servers" / server
    out_dir.mkdir(parents=True, exist_ok=True)
    names = []
    for tool in sorted(tools, key=lambda t: t["name"]):
        if tool["name"] in skip:
            continue
        fn, src = render(server, tool, source)
        (out_dir / f"{fn}.py").write_text(src, encoding="utf-8")
        names.append(fn)
    title = server.replace("_", " ")
    init = [f'"""{title} tools (generated). One tool per file; find them with codemode/search_tools.py."""', ""]
    init += [f"from .{n} import {n}" for n in names]
    init += ["", "__all__ = [" + ", ".join(repr(n) for n in names) + "]", ""]
    (out_dir / "__init__.py").write_text("\n".join(init), encoding="utf-8")
    return names


def main(argv: list[str]) -> int:
    if not argv or argv[0] in ("-h", "--help"):
        print(__doc__.strip())
        return 0 if argv else 2
    server = argv[0]
    if "--from" in argv:
        path = Path(argv[argv.index("--from") + 1]).resolve()
        tools = json.loads(path.read_text(encoding="utf-8"))["tools"]
        source = path.name if path.parent == KIT / "servers" / server else str(path)
    else:
        from codemode.runtime.mcp import session

        tools = session(server).list_tools()
        snapshot = KIT / "servers" / server / "tools.snapshot.json"
        snapshot.parent.mkdir(parents=True, exist_ok=True)
        snapshot.write_text(json.dumps({"_source": "live tools/list", "tools": tools}, indent=2) + "\n", encoding="utf-8")
        source = "live tools/list (snapshot in tools.snapshot.json)"
    names = generate(server, tools, source)
    print(f"{server}: wrote {len(names)} wrappers: {', '.join(names)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
